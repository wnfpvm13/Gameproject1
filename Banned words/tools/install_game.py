"""Builds tools/install_game.luau from src/: run that file in Studio's Edit datamodel to (re)install the game code.

Same layout as default.project.json, for places edited in Studio without Rojo (the test place is a cloud place).
The STT live test (tools/stt_live_test) is removed because its UI overlaps the game HUD.
"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")


def long_string(rel):
    text = io.open(os.path.join(SRC, rel), encoding="utf-8").read()
    assert "]====]" not in text, rel
    return "[====[" + text + "]====]"


def module(var, parent, name, rel, cls="ModuleScript"):
    return f'do local s = Instance.new("{cls}"); s.Name = "{name}"; s.Source = {long_string(rel)}; s.Parent = {parent} end\n'


code = """-- generated by tools/install_game.py; do not edit by hand
local RS = game:GetService("ReplicatedStorage")
local SSS = game:GetService("ServerScriptService")
local SPS = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
for _, old in {
	RS:FindFirstChild("BannedWords"), SSS:FindFirstChild("BannedWords"), SPS:FindFirstChild("BannedWordsClient"),
	RS:FindFirstChild("SttLiveTest"), SSS:FindFirstChild("SttLiveTestServer"), SPS:FindFirstChild("SttLiveTestClient"),
} do
	old:Destroy()
end
local shared = Instance.new("Folder"); shared.Name = "BannedWords"
local server = Instance.new("Folder"); server.Name = "BannedWords"
"""
code += module("", "shared", "Config", "shared/Config.luau")
code += module("", "shared", "Judge", "shared/Judge.luau")
code += module("", "server", "WordBank", "server/WordBank.luau")
code += module("", "server", "SeatService", "server/SeatService.luau")
code += module("", "server", "RoundService", "server/RoundService.luau")
code += module("", "server", "VoiceService", "server/VoiceService.luau")
code += module("", "server", "Prompts", "server/Prompts.luau")
code += module("", "server", "Main", "server/Main.server.luau", cls="Script")
code += """local client = Instance.new("LocalScript"); client.Name = "BannedWordsClient"
"""
code += f'client.Source = {long_string("client/Main.client.luau")}\n'
code += module("", "client", "Hud", "client/Hud.luau")
code += module("", "client", "Billboards", "client/Billboards.luau")
code += module("", "client", "Speech", "client/Speech.luau")
code += module("", "client", "ShowCamera", "client/ShowCamera.luau")
code += module("", "client", "FlatVoice", "client/FlatVoice.luau")
code += module("", "client", "Fx", "client/Fx.luau")
code += """shared.Parent = RS
server.Parent = SSS
client.Parent = SPS
game:GetService("VoiceChatService").UseAudioApi = Enum.AudioApiRollout.Enabled
return "game installed"
"""
io.open(os.path.join(HERE, "install_game.luau"), "w", encoding="utf-8", newline="\n").write(code)
print(len(code))
