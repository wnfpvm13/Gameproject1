"""Builds tools/install_game.luau from src/: run that file in Studio's Edit datamodel to (re)install the game code.

For places edited in Studio without Rojo (the test place is a cloud place). It follows the same rules as Rojo and
default.project.json, walking the folders, so a new module can never be left out of the installer:
  folder -> Folder, init.client.luau -> the folder becomes a LocalScript, X.server.luau -> Script,
  X.client.luau -> LocalScript, X.luau -> ModuleScript.
The map is separate (tools/build_lounge_map.luau, then tools/build_lounge_lighting.luau). The old STT live test is removed because its UI overlaps the HUD.
"""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(os.path.dirname(HERE), "src")

# (source folder, Roblox parent expression, instance name)
ROOTS = [
    ("shared", 'game:GetService("ReplicatedStorage")', "BannedWords"),
    ("server", 'game:GetService("ServerScriptService")', "BannedWords"),
    ("client", 'game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")', "BannedWordsClient"),
]


def long_string(path):
    text = io.open(path, encoding="utf-8").read()
    assert "]====]" not in text, path
    return "[====[" + text + "]====]"


def classify(filename):
    for suffix, cls in ((".server.luau", "Script"), (".client.luau", "LocalScript"), (".luau", "ModuleScript")):
        if filename.endswith(suffix):
            return filename[: -len(suffix)], cls
    return None, None


counter = [0]


def emit_folder(folder, parent_var, name, out):
    """Creates the instance for `folder` under parent_var; returns nothing (appends Luau lines to out)."""
    counter[0] += 1
    var = f"n{counter[0]}"
    init = os.path.join(folder, "init.client.luau")
    if os.path.exists(init):
        out.append(f'local {var} = Instance.new("LocalScript"); {var}.Name = "{name}"; {var}.Source = {long_string(init)}\n')
    else:
        out.append(f'local {var} = Instance.new("Folder"); {var}.Name = "{name}"\n')
    for entry in sorted(os.listdir(folder)):
        path = os.path.join(folder, entry)
        if os.path.isdir(path):
            emit_folder(path, var, entry, out)
        elif entry != "init.client.luau":
            child, cls = classify(entry)
            if child:
                out.append(f'do local s = Instance.new("{cls}"); s.Name = "{child}"; s.Source = {long_string(path)}; s.Parent = {var} end\n')
    out.append(f"{var}.Parent = {parent_var}\n")


out = ["-- generated by tools/install_game.py; do not edit by hand\n"]
out.append("local parents = {}\n")
for i, (_, parent, name) in enumerate(ROOTS):
    out.append(f"parents[{i + 1}] = {parent}\n")
out.append("""for _, pair in { { parents[1], "BannedWords" }, { parents[2], "BannedWords" }, { parents[3], "BannedWordsClient" },
	{ parents[1], "SttLiveTest" }, { parents[2], "SttLiveTestServer" }, { parents[3], "SttLiveTestClient" } } do
	local old = pair[1]:FindFirstChild(pair[2])
	if old then
		old:Destroy()
	end
end
""")
for i, (folder, _, name) in enumerate(ROOTS):
    emit_folder(os.path.join(SRC, folder), f"parents[{i + 1}]", name, out)
out.append('game:GetService("VoiceChatService").UseAudioApi = Enum.AudioApiRollout.Enabled\n')
# Chat participants' bubble/tag decoration needs the TextChatService chat. Scripts cannot switch ChatVersion (it needs
# RobloxScript capability): default.project.json sets it for Rojo builds, and here we can only warn.
out.append("""if game:GetService("TextChatService").ChatVersion ~= Enum.ChatVersion.TextChatService then
	return "game installed - WARNING: set TextChatService.ChatVersion to TextChatService in Studio (scripts cannot)"
end
return "game installed"
""")
code = "".join(out)
io.open(os.path.join(HERE, "install_game.luau"), "w", encoding="utf-8", newline="\n").write(code)
print(len(code))
