"""Builds install.luau: run it in Studio's Edit datamodel (via MCP execute_luau) to (re)create the live STT test."""
import io, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

def src(path):
    text = io.open(path, encoding="utf-8").read()
    assert "]====]" not in text
    return "[====[" + text + "]====]"

parts = {
    "judge": src(os.path.join(ROOT, "src/shared/Judge.luau")),
    "items": src(os.path.join(ROOT, "src/shared/LiveTestItems.luau")),
    "server": src(os.path.join(HERE, "LiveTestServer.server.luau")),
    "client": src(os.path.join(HERE, "LiveTestClient.client.luau")),
}
code = """-- generated by build_installer.py
local RS = game:GetService("ReplicatedStorage")
local SSS = game:GetService("ServerScriptService")
local SPS = game:GetService("StarterPlayer"):WaitForChild("StarterPlayerScripts")
for _, old in { RS:FindFirstChild("SttLiveTest"), SSS:FindFirstChild("SttLiveTestServer"), SPS:FindFirstChild("SttLiveTestClient") } do
	old:Destroy()
end
local folder = Instance.new("Folder"); folder.Name = "SttLiveTest"
local judge = Instance.new("ModuleScript"); judge.Name = "Judge"; judge.Source = %(judge)s; judge.Parent = folder
local items = Instance.new("ModuleScript"); items.Name = "LiveTestItems"; items.Source = %(items)s; items.Parent = folder
local ev = Instance.new("RemoteEvent"); ev.Name = "SttResult"; ev.Parent = folder
folder.Parent = RS
local server = Instance.new("Script"); server.Name = "SttLiveTestServer"; server.Source = %(server)s; server.Parent = SSS
local client = Instance.new("LocalScript"); client.Name = "SttLiveTestClient"; client.Source = %(client)s; client.Parent = SPS
game:GetService("VoiceChatService").UseAudioApi = Enum.AudioApiRollout.Enabled
return "installed"
""" % parts
io.open(os.path.join(HERE, "install.luau"), "w", encoding="utf-8", newline="\n").write(code)
print(len(code))
